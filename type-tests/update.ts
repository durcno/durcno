// ============================================================================
// Section 1: Column Update Value Type Inference (Static Type Assertions)
// ============================================================================

type UsersUpdate = InferUpdate<typeof Users>;
type EventsUpdate = InferUpdate<typeof Events>;
type LogsUpdate = InferUpdate<typeof Logs>;

// Primary key column should be excluded from update model
Expect<Equal<"id" extends keyof UsersUpdate ? true : false, false>>();

// Primary key column should be excluded from query builder update set object
type UsersSetParams = Parameters<
  ReturnType<typeof db.update<typeof Users>>["set"]
>[0];
Expect<Equal<"id" extends keyof UsersSetParams ? true : false, false>>();

// Generated BY DEFAULT column should be optional and allow bigint | null | undefined
Expect<Equal<EventsUpdate["autoId"], bigint | null | undefined>>();

// Not null column without default should be optional in update
Expect<Equal<UsersUpdate["username"], string | undefined>>();

// Not null column with default should be optional in update
Expect<Equal<UsersUpdate["createdAt"], Date | undefined>>();

// Default column without not null should allow value | null | undefined
Expect<Equal<EventsUpdate["description"], string | null | undefined>>();

// Nullable column without default should allow value | null | undefined
Expect<Equal<UsersUpdate["email"], string | null | undefined>>();

// Column with $updateFn should be optional in update
Expect<Equal<LogsUpdate["updatedAt"], Date | undefined>>();

// ============================================================================
// Section 2: Update Query Builder & Values (.set())
// ============================================================================

// Basic update returning null
const _basicUpdateQuery = db.update(Users).set({
  username: "new_username",
  email: "new@example.com",
});
type BasicUpdate = Awaited<typeof _basicUpdateQuery>;
Expect<Equal<BasicUpdate, null>>();

// Partial update (subset of columns)
const _partialUpdateQuery = db.update(Users).set({
  email: "updated@example.com",
});
type PartialUpdate = Awaited<typeof _partialUpdateQuery>;
Expect<Equal<PartialUpdate, null>>();

// Setting nullable field to explicit null
const _nullUpdateQuery = db.update(Users).set({
  email: null,
});
type NullUpdate = Awaited<typeof _nullUpdateQuery>;
Expect<Equal<NullUpdate, null>>();

// Setting optional field to explicit undefined
const _undefinedUpdateQuery = db.update(Users).set({
  username: "new_username",
  email: undefined,
});
type UndefinedUpdate = Awaited<typeof _undefinedUpdateQuery>;
Expect<Equal<UndefinedUpdate, null>>();

// Sql expression value in set
const _updateSqlValueQuery = db.update(Users).set({
  username: sql`LOWER(first_name)`,
});
type UpdateSqlValue = Awaited<typeof _updateSqlValueQuery>;
Expect<Equal<UpdateSqlValue, null>>();

// Column with $type override in set
const _updateMetricsQuery = db.update(Posts).set({
  metrics: { views: 200, likes: 100 },
});
type UpdateMetrics = Awaited<typeof _updateMetricsQuery>;
Expect<Equal<UpdateMetrics, null>>();

// Column with $updateFn omitted vs explicitly provided
db.update(Logs).set({ message: "Updated message" });
db.update(Logs).set({
  message: "Updated message",
  updatedAt: new Date("2026-01-01"),
});

// Update column with another column of compatible type
const _updateColumnValueQuery = db.update(Users).set({
  username: Users.externalId,
  email: Users.username,
});
type UpdateColumnValue = Awaited<typeof _updateColumnValueQuery>;
Expect<Equal<UpdateColumnValue, null>>();

// Update column with scalar SQL functions
const _updateScalarFnsQuery = db.update(Users).set({
  username: lower(Users.username),
  email: coalesce(Users.email, "fallback@example.com"),
});
type UpdateScalarFns = Awaited<typeof _updateScalarFnsQuery>;
Expect<Equal<UpdateScalarFns, null>>();

// Arithmetic scalar SQL functions on numeric columns
const _updateArithmeticQuery = db.update(CheckTest).set({
  quantity: add(CheckTest.quantity, 1),
});
type UpdateArithmetic = Awaited<typeof _updateArithmeticQuery>;
Expect<Equal<UpdateArithmetic, null>>();

