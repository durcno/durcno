import {
  add,
  and,
  caseWhen,
  coalesce,
  count,
  eq,
  gte,
  type InferUpdate,
  lower,
  sql,
} from "durcno";
import {
  CheckTest,
  db,
  type Events,
  Logs,
  Posts,
  UserProfiles,
  Users,
} from "./schema";
import { type Equal, Expect } from "./utils";

// -----------------------------------------------------------------------------
// Update model inference
// -----------------------------------------------------------------------------

type UsersUpdate = InferUpdate<typeof Users>;
type EventsUpdate = InferUpdate<typeof Events>;
type LogsUpdate = InferUpdate<typeof Logs>;

// Primary key is excluded from the update model
Expect<Equal<"id" extends keyof UsersUpdate ? true : false, false>>();

// Primary key is excluded from the `.set()` payload
type UsersSetParams = Parameters<
  ReturnType<typeof db.update<typeof Users>>["set"]
>[0];
Expect<Equal<"id" extends keyof UsersSetParams ? true : false, false>>();

// Generated BY DEFAULT column allows bigint | null | undefined
Expect<Equal<EventsUpdate["autoId"], bigint | null | undefined>>();

// Not null columns are optional in an update
Expect<Equal<UsersUpdate["username"], string | undefined>>();
Expect<Equal<UsersUpdate["createdAt"], Date | undefined>>();

// Default / nullable columns allow null and undefined
Expect<Equal<EventsUpdate["description"], string | null | undefined>>();
Expect<Equal<UsersUpdate["email"], string | null | undefined>>();

// Columns with `$updateFn` are optional
Expect<Equal<LogsUpdate["updatedAt"], Date | undefined>>();

// -----------------------------------------------------------------------------
// .set() values
// -----------------------------------------------------------------------------

// Basic, partial, null, and undefined values
const _basicUpdateQuery = db.update(Users).set({
  username: "new_username",
  email: null,
});
Expect<Equal<Awaited<typeof _basicUpdateQuery>, null>>();

const _undefinedUpdateQuery = db.update(Users).set({
  username: "new_username",
  email: undefined,
});
Expect<Equal<Awaited<typeof _undefinedUpdateQuery>, null>>();

// A `$updateFn` column may be omitted or set explicitly
db.update(Logs).set({ message: "Updated message" });
db.update(Logs).set({
  message: "Updated message",
  updatedAt: new Date("2026-01-01"),
});

// A `$type` override accepts its declared shape
const _updateMetricsQuery = db.update(Posts).set({
  metrics: { views: 200, likes: 100 },
});
Expect<Equal<Awaited<typeof _updateMetricsQuery>, null>>();

// @ts-expect-error - invalid enum value
db.update(Users).set({ type: "invalid_type" });

// @ts-expect-error - literal value does not match the column type
db.update(Users).set({ username: 123 });

// @ts-expect-error - non-existent column
db.update(Users).set({ nonExistentColumn: "value" });

// @ts-expect-error - mismatched `$type` override shape
db.update(Posts).set({ metrics: { views: "not-a-number" } });

// -----------------------------------------------------------------------------
// .set() expressions
// -----------------------------------------------------------------------------

// Raw SQL
const _updateSqlValueQuery = db.update(Users).set({
  username: sql`LOWER(first_name)`,
});
Expect<Equal<Awaited<typeof _updateSqlValueQuery>, null>>();

// Columns and scalar functions
const _updateColumnValueQuery = db.update(Users).set({
  username: Users.externalId,
  email: Users.username,
});
Expect<Equal<Awaited<typeof _updateColumnValueQuery>, null>>();

const _updateScalarFnsQuery = db.update(Users).set({
  username: lower(Users.username),
  email: coalesce(Users.email, "fallback@example.com"),
});
Expect<Equal<Awaited<typeof _updateScalarFnsQuery>, null>>();

// Arithmetic scalar functions
const _updateArithmeticQuery = db.update(CheckTest).set({
  quantity: add(CheckTest.quantity, 1),
});
Expect<Equal<Awaited<typeof _updateArithmeticQuery>, null>>();

// A CASE over plain columns is a scalar expression
const _setCase = db
  .update(Users)
  .set({ email: caseWhen(eq(Users.type, "admin"), Users.email) });
Expect<Equal<Awaited<typeof _setCase>, null>>();

// @ts-expect-error - column of an incompatible type (bigint -> string)
db.update(Users).set({ username: Users.id });

// @ts-expect-error - a nullable column cannot set a notNull column
db.update(Users).set({ username: Users.email });

// @ts-expect-error - a nullable function result cannot set a notNull column
db.update(Users).set({ username: lower(Users.email) });

// @ts-expect-error - an aggregate function is not a scalar value
db.update(Users).set({ username: count(Users.id) });

// @ts-expect-error - a column of another table
db.update(Users).set({ username: Posts.title });

// @ts-expect-error - a scalar function referencing another table
db.update(Users).set({ username: lower(Posts.title) });

// @ts-expect-error - number scalar function assigned to a bigint column
db.update(CheckTest).set({ price: add(CheckTest.price, 100n) });

// @ts-expect-error - a CASE over an aggregate is not scalar
db.update(Users).set({ email: caseWhen(eq(Users.type, "admin"), count("*")) });

// @ts-expect-error - an aggregate inside the CASE condition
db.update(Users).set({ email: caseWhen(gte(count("*"), 2), Users.email) });

// -----------------------------------------------------------------------------
// Where
// -----------------------------------------------------------------------------

const _updateWithWhereQuery = db
  .update(Users)
  .set({ username: "updated_user" })
  .where(and(eq(Users.id, 1n), eq(Users.type, "admin")));
Expect<Equal<Awaited<typeof _updateWithWhereQuery>, null>>();

// -----------------------------------------------------------------------------
// Returning
// -----------------------------------------------------------------------------

const _updateReturningQuery = db
  .update(Users)
  .set({ email: "updated@example.com" })
  .returning({ id: true, email: true });
type UpdateReturning = Awaited<typeof _updateReturningQuery>;
Expect<Equal<UpdateReturning, { id: bigint; email: string | null }[]>>();

db.update(Users)
  .set({ username: "test" })
  // @ts-expect-error - returning a non-existent column
  .returning({ nonExistentColumn: true });

// -----------------------------------------------------------------------------
// UPDATE ... FROM (bulk per-row writes)
// -----------------------------------------------------------------------------

// A values alias declared from source columns; rows are bound with `.as()`
const linkRows = db
  .values("v", {
    userId: UserProfiles.userId,
    bio: UserProfiles.bio,
  })
  .as([
    { userId: 1n, bio: "first" },
    { userId: 2n, bio: null },
    { userId: 3n, bio: undefined },
  ]);

// Bulk update assigning a distinct value per row
const _bulkFromValuesQuery = db
  .update(UserProfiles)
  .from(linkRows)
  .set({ bio: linkRows.bio })
  .where(eq(UserProfiles.userId, linkRows.userId))
  .returning({ userId: true, bio: true });
type BulkFromValues = Awaited<typeof _bulkFromValuesQuery>;
Expect<Equal<BulkFromValues, { userId: bigint; bio: string | null }[]>>();

// Bulk update without returning resolves to null
const _bulkFromValuesNoReturnQuery = db
  .update(UserProfiles)
  .from(linkRows)
  .set({ bio: linkRows.bio })
  .where(eq(UserProfiles.userId, linkRows.userId));
Expect<Equal<Awaited<typeof _bulkFromValuesNoReturnQuery>, null>>();

// The join key can sit on either side of the comparison
db.update(UserProfiles)
  .from(linkRows)
  .set({ bio: linkRows.bio })
  .where(eq(linkRows.userId, UserProfiles.id));

// FROM-source columns type-check per column
db.update(UserProfiles)
  .from(linkRows)
  // @ts-expect-error - bigint alias column cannot set a string column
  .set({ bio: linkRows.userId });

// An un-declared alias column cannot be referenced
db.update(UserProfiles)
  .from(linkRows)
  // @ts-expect-error - `linkOnly` is not a column of the updated table
  .set({ linkOnly: linkRows.userId });

// A plain table can be a FROM source
const _tableFromQuery = db
  .update(UserProfiles)
  .from(Users)
  .set({ bio: Users.username })
  .where(eq(UserProfiles.userId, Users.id));

// A CTE can be a FROM source when attached via db.with(...)
const totalsCte = db
  .with("totals")
  .as(
    db.from(Users).select(() => ({ userId: Users.id, name: Users.username })),
  );
const _cteFromQuery = db
  .with(totalsCte)
  .update(UserProfiles)
  .from(totalsCte)
  .set({ bio: totalsCte.name })
  .where(eq(UserProfiles.userId, totalsCte.userId));

// Repeated `.from()` calls append sources
db.update(UserProfiles)
  .from(linkRows)
  .from(Users)
  .set({ bio: linkRows.bio })
  .where(eq(UserProfiles.userId, linkRows.userId));

// `.from()` must precede `.set()`
db.update(UserProfiles)
  .set({ bio: "x" })
  // @ts-expect-error - `.from()` is a builder method, not a query method
  .from(linkRows);

// Row payloads are checked against the declared alias columns
db.values("v", { userId: UserProfiles.userId }).as([{ userId: 1n }]);
db.values("v", { bio: UserProfiles.bio }).as([{ bio: undefined }]);
db.values("v", { bio: UserProfiles.bio }).as([{ bio: null }]);
db.values("v", { userId: UserProfiles.userId }).as([
  // @ts-expect-error - a required (notNull) cell cannot be undefined
  { userId: undefined },
]);
db.values("v", { userId: UserProfiles.userId }).as([
  // @ts-expect-error - a wrong cell type
  { userId: "not-a-bigint" },
]);
db.values("v", { userId: UserProfiles.userId }).as([
  // @ts-expect-error - unknown row keys
  { userId: 1n, extra: 2n },
]);

// Prepared mode keeps the same shape, with `Arg`s accepted in set/where
const _preparedFromValuesQuery = db
  .prepare()
  .update(UserProfiles)
  .from(linkRows)
  .set({ bio: linkRows.bio })
  .where(eq(UserProfiles.userId, linkRows.userId));
